import { db } from "./firebase.js";
import { กันหน้า, เป็นผู้อนุมัติ, เป็นฝ่ายบุคคล } from "./auth.js";
import { มีคีย์ไหม, ถามAI } from "./ai.js";
import { doc, getDoc, updateDoc, deleteDoc, collection, getDocs, addDoc } from "https://www.gstatic.com/firebasejs/12.18.0/firebase-firestore.js";

// ผู้พิจารณาคือคนที่ล็อกอินอยู่จริง (spec US-08)
// เติมค่าหลัง กันหน้า() ตอบกลับมาแล้วเท่านั้น
var ผู้พิจารณา = null;

var รหัสใบลา = ค่าจากURL("id");
var กล่องใบลา = document.getElementById("กล่องใบลา");
var กล่องความเห็น = document.getElementById("กล่องความเห็น");

var ใบ = null;          // ใบลาที่กำลังเปิดอยู่
var ความเห็น = [];      // ความเห็นของใบนี้
var เตือนสถานะ = "";    // ข้อความบอกว่าเปลี่ยนสถานะไม่สำเร็จ

// ต้องล็อกอินก่อนถึงจะเปิดดูได้ · รอผลก่อนค่อยอ่านข้อมูล
var ผู้ใช้ = await กันหน้า();
if (ผู้ใช้) {
  ผู้พิจารณา = { id: ผู้ใช้.uid, name: ผู้ใช้.name };
  เปิดใบลา();
}

// ── ไปเอาใบลาใบนี้ พร้อมความเห็นในโฟลเดอร์ย่อยของมัน ──
async function เปิดใบลา() {
  if (!รหัสใบลา) {
    ไม่พบใบลา();
    return;
  }

  try {
    var ไฟล์ใบลา = await getDoc(doc(db, "leaveRequests", รหัสใบลา));

    if (!ไฟล์ใบลา.exists()) {
      ไม่พบใบลา();
      return;
    }

    // รหัสใบลาคือชื่อไฟล์ ไม่ใช่ช่องข้อมูลข้างใน จึงประกอบกลับเข้าไปเอง
    ใบ = Object.assign({ id: ไฟล์ใบลา.id }, ไฟล์ใบลา.data());

    // ความเห็นอยู่ในโฟลเดอร์ย่อย approvals ที่ซ้อนอยู่ในไฟล์ใบลาใบนี้
    var ผลความเห็น = await getDocs(collection(db, "leaveRequests", รหัสใบลา, "approvals"));
    ความเห็น = ผลความเห็น.docs.map(function (ไฟล์) {
      return Object.assign({ id: ไฟล์.id }, ไฟล์.data());
    });

    วาดใบลา();
    วาดความเห็น();
    await วาดกล่องAI();
    กล่องความเห็น.classList.remove("hidden");

    document.getElementById("ปุ่มส่งความเห็น").addEventListener("click", ส่งความเห็น);

  } catch (ข้อผิดพลาด) {
    // permission-denied ตรงนี้เกิดได้ 2 กรณี และทั้งคู่ควรตอบแบบเดียวกัน
    //   1. ไฟล์ไม่มีอยู่จริง — กฎอ่าน resource.data ไม่ได้เลยตีเป็นปฏิเสธ
    //   2. ไฟล์มีอยู่ แต่เป็นใบของคนอื่นที่เราไม่มีสิทธิ์เปิด
    // ตอบเหมือนกันทั้งสองกรณี จะได้ไม่บอกคนนอกว่าใบไหนมีอยู่จริงบ้าง
    if (ข้อผิดพลาด.code === "permission-denied") {
      ไม่พบใบลา();
      return;
    }
    กล่องใบลา.innerHTML = ข้อความผิดพลาดฐานข้อมูล(ข้อผิดพลาด);
  }
}

function ไม่พบใบลา() {
  กล่องใบลา.innerHTML =
    "<p>ไม่พบใบขอลาที่ต้องการ</p>" +
    '<p class="hint">อาจถูกลบไปแล้ว ลิงก์ไม่ถูกต้อง หรือคุณไม่มีสิทธิ์เปิดใบนี้</p>';
}

// ── วาดข้อมูลใบลาลงหน้าจอ ──
function วาดใบลา() {
  var แถว = [
    ["หัวข้อ", esc(ใบ.title)],
    ["เหตุผลการลา", esc(ใบ.reason)],
    ["ประเภทการลา", esc(ใบ.leaveTypeName)],
    ["วันที่ลา", esc(ใบ.startDate) + " ถึง " + esc(ใบ.endDate)],
    ["ผู้ขอลา", esc(ใบ.requesterName)],
    ["ผู้อนุมัติ", ใบ.approverName ? esc(ใบ.approverName) : "ยังไม่ได้กำหนดผู้อนุมัติ"],
    ["สถานะ", ป้ายสถานะ(ใบ.status)],
    ["วันที่ยื่น", esc(ใบ.createdAt)]
  ];

  var html = แถว.map(function (r) {
    return '<div class="field-row"><span class="k">' + r[0] + "</span><span>" + r[1] + "</span></div>";
  }).join("");

  // ปุ่มขึ้นตามบทบาทใน ACL.md · Rules กันซ้ำอยู่ชั้นล่างแล้ว ตรงนี้แค่ไม่ให้หน้าจอหลอกผู้ใช้
  //   อนุมัติ/ไม่อนุมัติ → เฉพาะผู้อนุมัติและฝ่ายบุคคล · ผู้ขอลากดใบตัวเองไม่ได้
  //   ลบ                → เจ้าของใบ หรือฝ่ายบุคคล · ผู้อนุมัติลบใบคนอื่นไม่ได้
  var ยังรอพิจารณา = ใบ.status === "รอพิจารณา";
  var เปลี่ยนสถานะได้ = ยังรอพิจารณา && เป็นผู้อนุมัติ(ผู้ใช้);
  var ลบได้ = ใบ.requesterId === ผู้ใช้.uid || เป็นฝ่ายบุคคล(ผู้ใช้);

  html += '<div class="btn-row">';
  if (เปลี่ยนสถานะได้) {
    html +=
      '<button type="button" class="btn-ok" id="ปุ่มอนุมัติ">อนุมัติ</button>' +
      '<button type="button" class="btn-danger" id="ปุ่มไม่อนุมัติ">ไม่อนุมัติ</button>';
  }
  if (ลบได้) {
    html +=
      '<button type="button" class="btn-danger" id="ปุ่มลบ"' + (ยังรอพิจารณา ? "" : " disabled") +
      ">ลบใบลา</button>";
  }
  html += "</div>";

  if (!ยังรอพิจารณา) {
    html += '<p class="hint">ใบนี้พิจารณาแล้ว จึงเปลี่ยนสถานะต่อไม่ได้ และลบไม่ได้ — ลบได้เฉพาะใบที่ยังรอพิจารณา</p>';
  } else if (!เป็นผู้อนุมัติ(ผู้ใช้)) {
    html += '<p class="hint">ใบนี้รอผู้อนุมัติพิจารณาอยู่ — ผู้ขอลาเปลี่ยนสถานะใบของตัวเองไม่ได้</p>';
  }

  if (เตือนสถานะ) {
    html += '<div class="alert alert-error">' + เตือนสถานะ + "</div>";
  }

  กล่องใบลา.innerHTML = html;

  if (เปลี่ยนสถานะได้) {
    document.getElementById("ปุ่มอนุมัติ").addEventListener("click", function () { เปลี่ยนสถานะ("อนุมัติ"); });
    document.getElementById("ปุ่มไม่อนุมัติ").addEventListener("click", function () { เปลี่ยนสถานะ("ไม่อนุมัติ"); });
  }
  if (ลบได้ && ยังรอพิจารณา) {
    document.getElementById("ปุ่มลบ").addEventListener("click", ลบใบลา);
  }
}

// ── เปลี่ยนสถานะ แล้วบันทึกลง Firestore ──
async function เปลี่ยนสถานะ(สถานะใหม่) {
  // กฎ: จะไม่อนุมัติได้ ต้องมีความเห็นอย่างน้อย 1 รายการก่อน
  if (สถานะใหม่ === "ไม่อนุมัติ" && ความเห็น.length === 0) {
    alert("ต้องเขียนความเห็นอย่างน้อย 1 รายการก่อน จึงจะกดไม่อนุมัติได้");
    return;
  }

  // ส่ง id ปุ่มที่กดไปด้วย ไม่งั้นข้อความ "กำลังบันทึก…" จะไปขึ้นบนปุ่มอนุมัติเสมอ
  ปิดปุ่มพิจารณา("กำลังบันทึก…", สถานะใหม่ === "อนุมัติ" ? "ปุ่มอนุมัติ" : "ปุ่มไม่อนุมัติ");

  try {
    // 🔑 updateDoc ส่งไปเฉพาะช่อง status ช่องเดียว อีก 11 ช่องคงเดิมทั้งหมด
    //    spec หัวข้อ 6 สั่งไว้ว่าห้ามเขียนทับช่องอื่นตอนเปลี่ยนสถานะ
    //    (ถ้าใช้ setDoc จะกลายเป็นลบช่องอื่นทิ้งทั้งไฟล์)
    await updateDoc(doc(db, "leaveRequests", ใบ.id), { status: สถานะใหม่ });

    // เขียนสำเร็จแล้วค่อยเปลี่ยนหน้าจอตาม
    ใบ.status = สถานะใหม่;
    เตือนสถานะ = "";
    วาดใบลา();

  } catch (ข้อผิดพลาด) {
    // เขียนไม่สำเร็จ สถานะในฐานยังเป็นค่าเดิม หน้าจอจึงต้องไม่เปลี่ยนตาม
    console.error("เปลี่ยนสถานะไม่สำเร็จ:", ข้อผิดพลาด);
    เตือนสถานะ = "⚠️ เปลี่ยนสถานะไม่สำเร็จ ใบลายังเป็น " + esc(ใบ.status) +
                 " เหมือนเดิม (" + esc(ข้อผิดพลาด.code || ข้อผิดพลาด.message) + ")";
    วาดใบลา();
  }
}

// ปิดปุ่มทุกปุ่มระหว่างบันทึก กันกดรัวแล้วสั่งซ้ำ
// idที่เปลี่ยนข้อความ คือปุ่มที่จะขึ้นว่ากำลังทำอะไรอยู่
function ปิดปุ่มพิจารณา(ข้อความ, idที่เปลี่ยนข้อความ) {
  ["ปุ่มอนุมัติ", "ปุ่มไม่อนุมัติ", "ปุ่มลบ"].forEach(function (id) {
    var ปุ่ม = document.getElementById(id);
    if (ปุ่ม) { ปุ่ม.disabled = true; }
  });
  var ปุ่มที่บอกสถานะ = document.getElementById(idที่เปลี่ยนข้อความ || "ปุ่มอนุมัติ");
  if (ปุ่มที่บอกสถานะ) { ปุ่มที่บอกสถานะ.textContent = ข้อความ; }
}

// ── 🤖 ข้อเสนอจาก AI ──
// 🔴 ปุ่มนี้เขียนได้เฉพาะช่อง aiSuggestion เท่านั้น
//    ห้ามให้ AI เปลี่ยน status เอง สถานะจริงต้องรอคนกดอนุมัติ/ไม่อนุมัติเท่านั้น
//    (firestore.rules กันไว้อีกชั้น ถึงโค้ดพลาดก็เขียนไม่ผ่าน)
async function วาดกล่องAI() {
  var กล่องAI = document.getElementById("กล่องAI");
  var ที่วางสรุป = document.getElementById("ที่วางสรุป");
  var แถวปุ่ม = document.getElementById("แถวปุ่มAI");

  var กดสรุปได้ = เป็นผู้อนุมัติ(ผู้ใช้) && (await มีคีย์ไหม());

  // ไม่มีสรุปเก่า และกดสร้างก็ไม่ได้ ก็ไม่ต้องโชว์กล่องนี้เลย
  if (!ใบ.aiSuggestion && !กดสรุปได้) return;

  ที่วางสรุป.innerHTML = ใบ.aiSuggestion
    ? '<div class="alert alert-ai">' + esc(ใบ.aiSuggestion) + "</div>"
    : '<p class="hint">ยังไม่มีสรุป — กดปุ่มด้านล่างเพื่อให้ AI สรุปใบลานี้</p>';

  แถวปุ่ม.innerHTML = กดสรุปได้
    ? '<button type="button" id="ปุ่มสรุป">' + (ใบ.aiSuggestion ? "สรุปใหม่อีกครั้ง" : "ให้ AI สรุปใบลานี้") + "</button>"
    : "";

  if (กดสรุปได้) {
    document.getElementById("ปุ่มสรุป").addEventListener("click", สั่งAIสรุป);
  }
  กล่องAI.classList.remove("hidden");
}

// สร้างคำสั่งจากข้อมูลในใบลา รวมความเห็นที่มีอยู่ด้วย
function คำสั่งสรุป() {
  var รายการความเห็น = ความเห็น.length
    ? ความเห็น.map(function (c) { return "- " + c.authorName + ": " + c.message; }).join("\n")
    : "(ยังไม่มีความเห็น)";

  return "คุณคือผู้ช่วยของหัวหน้างาน สรุปใบขอลาต่อไปนี้ให้หัวหน้าอ่านก่อนตัดสินใจอนุมัติ\n\n" +
    "หัวข้อ: " + ใบ.title + "\n" +
    "ผู้ขอลา: " + ใบ.requesterName + "\n" +
    "ประเภทการลา: " + ใบ.leaveTypeName + "\n" +
    "วันที่ลา: " + ใบ.startDate + " ถึง " + ใบ.endDate + "\n" +
    "เหตุผล: " + ใบ.reason + "\n" +
    "ความเห็นที่มีอยู่:\n" + รายการความเห็น + "\n\n" +
    "เขียนสรุปภาษาไทย 2-3 ประโยค เน้นสิ่งที่หัวหน้าต้องรู้ก่อนตัดสินใจ\n" +
    "ห้ามแต่งข้อมูลที่ไม่มีในใบลา และห้ามบอกว่าควรอนุมัติหรือไม่อนุมัติ";
}

async function สั่งAIสรุป() {
  var ปุ่ม = document.getElementById("ปุ่มสรุป");
  var ที่วางสรุป = document.getElementById("ที่วางสรุป");
  var ข้อความเดิมบนปุ่ม = ปุ่ม.textContent;

  ปุ่ม.disabled = true;
  ปุ่ม.textContent = "กำลังให้ AI สรุป…";

  var คำสั่ง = คำสั่งสรุป();
  var ผล = await ถามAI(คำสั่ง);

  // บันทึกร่องรอยทุกครั้งที่เรียก ไม่ว่าสำเร็จหรือไม่
  await บันทึกaiLog(คำสั่ง, ผล.สำเร็จ ? ผล.ข้อความ : "ไม่สำเร็จ — " + ผล.เหตุผล);

  if (!ผล.สำเร็จ) {
    // AI พลาดไม่กระทบอย่างอื่น ปุ่มอนุมัติยังกดได้ตามปกติ
    ที่วางสรุป.innerHTML = '<div class="alert alert-error">⚠️ สรุปไม่สำเร็จ — ' + esc(ผล.เหตุผล) + "</div>" +
      (ใบ.aiSuggestion ? '<div class="alert alert-ai">' + esc(ใบ.aiSuggestion) + "</div>" : "");
    ปุ่ม.disabled = false;
    ปุ่ม.textContent = ข้อความเดิมบนปุ่ม;
    return;
  }

  try {
    // เขียนเฉพาะช่อง aiSuggestion ช่องเดียว ไม่แตะ status
    await updateDoc(doc(db, "leaveRequests", ใบ.id), { aiSuggestion: ผล.ข้อความ });

    // เขียนสำเร็จแล้วค่อยเปลี่ยนหน้าจอ
    ใบ.aiSuggestion = ผล.ข้อความ;
    await วาดกล่องAI();

  } catch (ข้อผิดพลาด) {
    console.error("บันทึกสรุปไม่สำเร็จ:", ข้อผิดพลาด);
    ที่วางสรุป.innerHTML = '<div class="alert alert-error">⚠️ AI สรุปมาแล้ว แต่บันทึกลงฐานไม่สำเร็จ — ' +
      esc(ข้อผิดพลาด.code || ข้อผิดพลาด.message) + "</div>" +
      '<div class="alert alert-ai">' + esc(ผล.ข้อความ) + "</div>";
    ปุ่ม.disabled = false;
    ปุ่ม.textContent = ข้อความเดิมบนปุ่ม;
  }
}

// เก็บร่องรอยการเรียก AI ไว้ในโฟลเดอร์ย่อย aiLog ของใบลาใบนี้
// ⚠️ เขียน log ไม่สำเร็จต้องไม่ทำให้ฟีเจอร์หลักพัง จึงกลืนข้อผิดพลาดไว้เงียบ ๆ
async function บันทึกaiLog(ข้อความที่ส่ง, ข้อความที่ได้) {
  try {
    await addDoc(collection(db, "leaveRequests", ใบ.id, "aiLog"), {
      input: ข้อความที่ส่ง,
      output: ข้อความที่ได้,
      createdAt: เวลาตอนนี้()
    });
  } catch (ข้อผิดพลาด) {
    console.error("บันทึก aiLog ไม่สำเร็จ (ไม่กระทบการทำงานหลัก):", ข้อผิดพลาด);
  }
}

// ── ลบใบลา ──
// ⚠️ Firestore ไม่ลบโฟลเดอร์ย่อยให้อัตโนมัติ
//    ถ้าลบแต่ไฟล์ใบลา ความเห็นใน approvals จะค้างอยู่ในฐานตลอดไป
//    มองไม่เห็นทั้งจากหน้าเว็บและจาก Console เพราะไฟล์แม่หายไปแล้ว
//    จึงต้องลบไฟล์ในโฟลเดอร์ย่อยให้หมดก่อน แล้วค่อยลบไฟล์ใบลา
//    ตอนนี้มี 2 โฟลเดอร์ย่อย: approvals และ aiLog — เพิ่มโฟลเดอร์ย่อยใหม่เมื่อไหร่ต้องมาเติมที่นี่ด้วย
async function ลบใบลา() {
  // ด่านที่สอง — ปุ่มที่ปิดไว้ในหน้าเว็บ ผู้ใช้สั่งข้ามได้จาก F12
  // (การกันจริงจังทำด้วย Security Rules ในสัปดาห์ที่ 8)
  if (ใบ.status !== "รอพิจารณา") {
    alert("ลบได้เฉพาะใบที่สถานะยังเป็น รอพิจารณา");
    return;
  }

  var คำถาม = 'ยืนยันลบใบลา "' + ใบ.title + '" หรือไม่';
  if (ความเห็น.length > 0) {
    คำถาม += "\nความเห็น " + ความเห็น.length + " รายการในใบนี้จะถูกลบไปด้วย และกู้คืนไม่ได้";
  }
  if (!confirm(คำถาม)) return;

  ปิดปุ่มพิจารณา("กำลังลบ…", "ปุ่มลบ");

  try {
    // 1) ลบทุกไฟล์ในโฟลเดอร์ย่อยให้หมดก่อน ทั้ง approvals และ aiLog
    for (var ชื่อโฟลเดอร์ย่อย of ["approvals", "aiLog"]) {
      var ไฟล์ทั้งหมด = await getDocs(collection(db, "leaveRequests", ใบ.id, ชื่อโฟลเดอร์ย่อย));
      for (var ไฟล์ย่อย of ไฟล์ทั้งหมด.docs) {
        await deleteDoc(ไฟล์ย่อย.ref);
      }
    }

    // 2) แล้วค่อยลบไฟล์ใบลา
    await deleteDoc(doc(db, "leaveRequests", ใบ.id));

    // 3) ลบสำเร็จแล้วค่อยพากลับหน้ารายการ
    location.href = "leave-requests.html";

  } catch (ข้อผิดพลาด) {
    // ลบไม่สำเร็จ อยู่หน้าเดิม กดลบซ้ำได้ ระบบจะลบต่อจากที่ค้างไว้
    console.error("ลบใบลาไม่สำเร็จ:", ข้อผิดพลาด);
    เตือนสถานะ = "⚠️ ลบใบลาไม่สำเร็จ ใบลายังอยู่ในระบบ กดลบอีกครั้งได้ (" +
                 esc(ข้อผิดพลาด.code || ข้อผิดพลาด.message) + ")";
    วาดใบลา();
  }
}

// ── รายการความเห็น เรียงจากเก่าไปใหม่ ──
function วาดความเห็น() {
  var ที่วาง = document.getElementById("รายการความเห็น");
  if (ความเห็น.length === 0) {
    ที่วาง.innerHTML = "<p>ยังไม่มีความเห็นในใบนี้</p>";
    return;
  }
  ที่วาง.innerHTML = ความเห็น
    .slice()
    .sort(function (a, b) { return a.createdAt < b.createdAt ? -1 : 1; })
    .map(function (c) {
      return '<div class="comment"><div class="meta">' + esc(c.authorName) + " · " + esc(c.createdAt) +
             "</div><div>" + esc(c.message) + "</div></div>";
    }).join("");
}

// ── ส่งความเห็นใหม่ ลงโฟลเดอร์ย่อย approvals ของใบนี้ ──
async function ส่งความเห็น() {
  var ช่อง = document.getElementById("ข้อความความเห็น");
  var เตือน = document.getElementById("เตือนความเห็น");
  var ปุ่มส่ง = document.getElementById("ปุ่มส่งความเห็น");
  var ข้อความ = ช่อง.value.trim();

  if (!ข้อความ) {
    เตือน.textContent = "⚠️ พิมพ์ข้อความก่อน จึงจะส่งความเห็นได้";
    เตือน.classList.remove("hidden");
    return;
  }
  เตือน.classList.add("hidden");

  ปุ่มส่ง.disabled = true;
  ปุ่มส่ง.textContent = "กำลังส่ง…";

  // ไม่ใส่ช่อง requestId เพราะการที่ไฟล์นี้อยู่ในโฟลเดอร์ย่อยของใบไหน
  // ก็บอกอยู่แล้วว่าเป็นความเห็นของใบนั้น
  var ความเห็นใหม่ = {
    authorId: ผู้พิจารณา.id,
    authorName: ผู้พิจารณา.name,
    message: ข้อความ,
    createdAt: เวลาตอนนี้()
  };

  try {
    var ไฟล์ใหม่ = await addDoc(collection(db, "leaveRequests", ใบ.id, "approvals"), ความเห็นใหม่);

    // บันทึกสำเร็จแล้วค่อยล้างช่องข้อความและเติมลงรายการ
    ความเห็น.push(Object.assign({ id: ไฟล์ใหม่.id }, ความเห็นใหม่));
    ช่อง.value = "";
    วาดความเห็น();

  } catch (ข้อผิดพลาด) {
    // ส่งไม่สำเร็จ ไม่ล้างช่องข้อความ ผู้ใช้จะได้ไม่ต้องพิมพ์ใหม่
    เตือน.innerHTML = "<p>ส่งความเห็นไม่สำเร็จ ความเห็นยังไม่ถูกบันทึก</p>" +
                      ข้อความผิดพลาดฐานข้อมูล(ข้อผิดพลาด);
    เตือน.classList.remove("hidden");
  }

  ปุ่มส่ง.disabled = false;
  ปุ่มส่ง.textContent = "ส่งความเห็น";
}
