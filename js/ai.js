// 🔴 คีย์อยู่ใน js/ai-key.js ซึ่งไม่ถูก commit และไม่ถูก deploy
//    บนเว็บจริงจะไม่มีไฟล์นั้น → มีคีย์ไหม() คืน false → หน้าเว็บซ่อนปุ่ม AI
//    ที่เหลือของหน้ายังทำงานปกติ ไม่พังทั้งหน้า
//
// ⚠️ โค้ดที่รันในเบราว์เซอร์ซ่อนคีย์ไม่ได้ ใครเปิด F12 ก็เห็น
//    ปุ่ม AI จึงใช้ได้เฉพาะเครื่องที่มีไฟล์คีย์เท่านั้น
// ─────────────────────────────────────────────────────────────

var วินาทีที่รอได้ = 15;   // spec US-09 — เรียกไม่สำเร็จหรือรอเกิน 15 วินาที ระบบต้องไม่ค้าง
var คีย์ที่โหลดได้ = undefined;   // undefined = ยังไม่เคยลอง · null = ไม่มีไฟล์คีย์

// ── โหลดไฟล์คีย์แบบยืดหยุ่น ──
// ใช้ import() แบบเรียกตอนใช้งาน ไม่ใช่ import ตายตัวบนหัวไฟล์
// เพราะถ้าไฟล์ไม่มี import ตายตัวจะทำให้ทั้งโมดูลพัง
async function โหลดคีย์() {
  if (คีย์ที่โหลดได้ !== undefined) return คีย์ที่โหลดได้;
  try {
    var ไฟล์ = await import("./ai-key.js");
    var ค่า = { คีย์: ไฟล์.คีย์, โมเดล: ไฟล์.โมเดล };
    คีย์ที่โหลดได้ = (ค่า.คีย์ && ค่า.คีย์.indexOf("ใส่คีย์ของคุณ") === -1) ? ค่า : null;
  } catch (ข้อผิดพลาด) {
    // ไม่มีไฟล์คีย์ ถือว่าเครื่องนี้ใช้ AI ไม่ได้ ไม่ใช่ข้อผิดพลาดที่ต้องโวยวาย
    คีย์ที่โหลดได้ = null;
  }
  return คีย์ที่โหลดได้;
}

export async function มีคีย์ไหม() {
  return (await โหลดคีย์()) !== null;
}

// ── ถาม AI แล้วคืนข้อความตอบกลับ ──
// สำเร็จ → { สำเร็จ: true, ข้อความ, โมเดล, วินาทีที่ใช้ }
// พลาด   → { สำเร็จ: false, เหตุผล }   ← เหตุผลเป็นภาษาคน เอาไปแสดงได้เลย
export async function ถามAI(คำสั่ง) {
  var ค่าคีย์ = await โหลดคีย์();
  if (!ค่าคีย์) {
    return { สำเร็จ: false, เหตุผล: "เครื่องนี้ยังไม่ได้ตั้งค่าคีย์ AI (ไม่มีไฟล์ js/ai-key.js)" };
  }

  var ตัวยกเลิก = new AbortController();
  var ตัวจับเวลา = setTimeout(function () { ตัวยกเลิก.abort(); }, วินาทีที่รอได้ * 1000);
  var เริ่มเมื่อ = Date.now();

  try {
    var คำตอบดิบ = await fetch("https://openrouter.ai/api/v1/chat/completions", {
      method: "POST",
      signal: ตัวยกเลิก.signal,
      headers: {
        "Authorization": "Bearer " + ค่าคีย์.คีย์,
        "Content-Type": "application/json"
      },
      body: JSON.stringify({
        model: ค่าคีย์.โมเดล,
        messages: [{ role: "user", content: คำสั่ง }]
      })
    });

    var ข้อมูล = await คำตอบดิบ.json();

    if (!คำตอบดิบ.ok) {
      var จากปลายทาง = (ข้อมูล.error && ข้อมูล.error.message) || คำตอบดิบ.statusText;
      return { สำเร็จ: false, เหตุผล: แปลรหัส(คำตอบดิบ.status) + " (" + จากปลายทาง + ")" };
    }

    var ข้อความ = ข้อมูล.choices && ข้อมูล.choices[0] &&
                  ข้อมูล.choices[0].message && ข้อมูล.choices[0].message.content;

    if (!ข้อความ) {
      return { สำเร็จ: false, เหตุผล: "เรียกสำเร็จ แต่ AI ไม่ได้ตอบข้อความกลับมา" };
    }

    return {
      สำเร็จ: true,
      ข้อความ: ข้อความ.trim(),
      โมเดล: ข้อมูล.model || ค่าคีย์.โมเดล,
      วินาทีที่ใช้: ((Date.now() - เริ่มเมื่อ) / 1000).toFixed(1)
    };

  } catch (ข้อผิดพลาด) {
    if (ข้อผิดพลาด.name === "AbortError") {
      return { สำเร็จ: false, เหตุผล: "รอเกิน " + วินาทีที่รอได้ + " วินาทีแล้วยังไม่ตอบ จึงยกเลิกการรอ" };
    }
    console.error("เรียก OpenRouter ไม่สำเร็จ:", ข้อผิดพลาด);
    return { สำเร็จ: false, เหตุผล: "ต่อไปหา OpenRouter ไม่ได้ — " + ข้อผิดพลาด.message };
  } finally {
    clearTimeout(ตัวจับเวลา);
  }
}

// แปลรหัสที่เจอบ่อยเป็นภาษาคน จะได้ไม่ต้องไปเปิดคู่มือ
function แปลรหัส(รหัส) {
  if (รหัส === 401) return "คีย์ไม่ถูกต้องหรือถูกเพิกถอนแล้ว";
  if (รหัส === 402) return "เครดิตในบัญชี OpenRouter หมด";
  if (รหัส === 404) return "ไม่รู้จักชื่อโมเดลนี้";
  if (รหัส === 429) return "เรียกถี่เกินไป รอสักครู่แล้วลองใหม่";
  if (รหัส >= 500) return "ฝั่ง OpenRouter มีปัญหา ไม่ใช่ที่โค้ดเรา";
  return "เรียกไม่สำเร็จ (รหัส " + รหัส + ")";
}
