// แปลงข้อความของผู้ใช้ให้ปลอดภัยก่อนเอาไปวางในหน้าเว็บ
// ถ้าไม่ทำ ข้อความที่มีเครื่องหมาย < > จะทำให้หน้าเว็บเพี้ยนได้
function esc(ข้อความ) {
  return String(ข้อความ == null ? "" : ข้อความ)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

// ป้ายสถานะสี — รอพิจารณา=เหลือง อนุมัติ=เขียว ไม่อนุมัติ=แดง
function ป้ายสถานะ(สถานะ) {
  return '<span class="badge badge-' + esc(สถานะ) + '">' + esc(สถานะ) + "</span>";
}

// เวลาปัจจุบันในรูปแบบเดียวกับข้อมูลตัวอย่าง เช่น "2026-09-01 09:15"
// เก็บเป็นข้อความเพื่อให้เรียงลำดับและอ่านง่ายโดยไม่ต้องแปลงชนิดข้อมูล
function เวลาตอนนี้() {
  var d = new Date();
  var สองหลัก = function (n) { return String(n).padStart(2, "0"); };
  return d.getFullYear() + "-" + สองหลัก(d.getMonth() + 1) + "-" + สองหลัก(d.getDate()) +
         " " + สองหลัก(d.getHours()) + ":" + สองหลัก(d.getMinutes());
}

// อ่านค่าที่ต่อท้าย URL เช่น leave-request-detail.html?id=lr001
function ค่าจากURL(ชื่อ) {
  return new URLSearchParams(location.search).get(ชื่อ) || "";
}

// ข้อความอธิบายเวลาต่อฐานข้อมูลไม่สำเร็จ · ใช้ร่วมกันทุกหน้าที่อ่านจาก Firestore
// คืนค่าเป็น HTML ให้แต่ละหน้าเอาไปวางในกล่องของตัวเอง
function ข้อความผิดพลาดฐานข้อมูล(ข้อผิดพลาด) {
  var รหัส = ข้อผิดพลาด.code || "";
  var คำแนะนำ;

  if (รหัส === "permission-denied") {
    คำแนะนำ = "กฎของ Firestore ไม่ยอมให้อ่าน — ถ้าเปิดโหมดทดสอบไว้ อาจครบ 30 วันแล้ว ให้ไปต่ออายุที่ Firebase Console หัวข้อ Rules";
  } else if (รหัส === "unavailable" || รหัส === "failed-precondition") {
    คำแนะนำ = "ติดต่อฐานข้อมูลไม่ได้ — ตรวจว่าเปิด Firestore Database ในโปรเจกต์นี้แล้วหรือยัง และเน็ตต่ออยู่ไหม";
  } else {
    คำแนะนำ = "ลองเปิด Console ของเบราว์เซอร์ (กด F12) เพื่อดูรายละเอียดเพิ่ม";
  }

  console.error("อ่านข้อมูลจาก Firestore ไม่สำเร็จ:", ข้อผิดพลาด);

  return "<p>⚠️ อ่านข้อมูลจากฐานข้อมูลไม่สำเร็จ</p>" +
         '<p class="hint">' + esc(คำแนะนำ) + "</p>" +
         '<p class="hint">รายละเอียด: ' + esc(รหัส || ข้อผิดพลาด.message) + "</p>";
}
